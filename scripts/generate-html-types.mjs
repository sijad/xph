import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const require = createRequire(new URL('../packages/language-server/package.json', import.meta.url));
const { getDefaultHTMLDataProvider } = require('vscode-html-languageservice');
const provider = getDefaultHTMLDataProvider();
const unique = (attributes) => [
	...new Map(attributes.map((attribute) => [attribute.name, attribute])).values(),
];
const globals = unique(provider.provideAttributes('')).filter(
	(attribute) => !/^on/i.test(attribute.name),
);
const names = new Set(globals.map((attribute) => attribute.name));
const numeric = new Set(
	(
		'tabindex width height rows cols rowspan colspan span size maxlength minlength min max step ' +
		'start high low optimum value results border cellpadding cellspacing marginheight marginwidth ' +
		'aria-colcount aria-colindex aria-colspan aria-level aria-posinset aria-rowcount aria-rowindex ' +
		'aria-rowspan aria-setsize aria-valuemax aria-valuemin aria-valuenow'
	).split(' '),
);
// Completion lists for these attributes are suggestions, not exhaustive values:
// several accept space-separated tokens, custom names or user-defined values.
const openValues = new Set(
	(
		'autocomplete target formtarget rel rev sandbox sizes blocking role dropzone ' +
		'http-equiv aria-relevant aria-dropeffect'
	).split(' '),
);
function attributeType(tag, attribute) {
	const name = attribute.name;
	if (name === 'style') return 'string | Record<string, string | number | null | undefined> | null';
	if (name === 'contenteditable')
		return 'boolean | "" | "true" | "false" | "inherit" | "plaintext-only" | null';
	if (attribute.valueSet === 'v' || name === 'download') return 'boolean | string | null';
	if (numeric.has(name)) return 'number | string | null';
	const values = [...new Set(provider.provideValues(tag, name).map((value) => value.name))];
	if (!values.length) return 'string | null';
	const types = values.map((value) => JSON.stringify(value));
	if (values.includes('true') && values.includes('false')) types.unshift('boolean');
	if (openValues.has(name)) types.push('(string & {})');
	return [...types, 'null'].join(' | ');
}
const property = (attribute, tag = '') =>
	`\t${JSON.stringify(attribute.name)}?: ${attributeType(tag, attribute)};\n`;
let source =
	'// Native HTML and SVG declarations for editor navigation.\n' +
	'// Generated by scripts/generate-html-types.mjs; format with pnpm format.\n' +
	'export interface HTMLAttributes {\n' +
	globals.map((attribute) => property(attribute)).join('') +
	'}\n\nexport interface Elements {\n';
for (const tag of provider.provideTags()) {
	const attributes = unique(provider.provideAttributes(tag.name)).filter(
		(attribute) => !names.has(attribute.name) && !/^on/i.test(attribute.name),
	);
	source +=
		`\t${JSON.stringify(tag.name)}: HTMLAttributes & {\n` +
		attributes.map((attribute) => '\t' + property(attribute, tag.name)).join('') +
		'\t};\n';
}
const ts = require('typescript');
const filename = resolve(dirname(ts.getDefaultLibFilePath({})), 'lib.dom.d.ts');
const dom = ts.createSourceFile(
	filename,
	await readFile(filename, 'utf8'),
	ts.ScriptTarget.Latest,
	true,
);
const svg = dom.statements.find(
	(node) => ts.isInterfaceDeclaration(node) && node.name.text === 'SVGElementTagNameMap',
);
source += '}\n\nexport interface SVGElements {\n';
for (const member of svg?.members ?? []) {
	if (ts.isPropertySignature(member) && ts.isStringLiteral(member.name))
		source += `\t${JSON.stringify(member.name.text)}: HTMLAttributes & {};\n`;
}
await writeFile(
	new URL('../packages/language-server/src/xph.d.ts', import.meta.url),
	source + '}\n',
);
